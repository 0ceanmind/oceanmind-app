#!/usr/bin/env node
/**
 * Stage a deployable copy of OceanMind in PITCH-DEMO mode, for its own Vercel
 * project (separate from production). It does NOT deploy.
 *
 *   node scripts/stage-demo-deploy.mjs [outDir]
 *
 * The copy is the app as it is on disk, minus local-only folders, with one
 * change: api/index.js first imports api/_demo-env.js, which switches demo
 * mode on (OCEANMIND_DEMO=1) and drops DATABASE_URL before server/app.js — and
 * with it db.js — is evaluated (ESM runs imports in order). Files starting
 * with "_" in api/ are not turned into functions by Vercel. The .vercel link
 * is left out on purpose so the copy can never deploy over production.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUT = 'C:\\Users\\Faisal\\AppData\\Local\\Temp\\claude\\C--Users-Faisal-Desktop-OceanMind\\d8b0e33d-cde8-4a51-a43a-bbc5d272f182\\scratchpad\\demo-deploy';
const OUT = resolve(process.argv[2] ?? DEFAULT_OUT);

// relative to the app root, forward slashes
const EXCLUDE = new Set([
  'node_modules', '.git', '.vercel', '.audit', '.backup-pre-recovery',
  'server/data', 'client/node_modules', 'client/dist', '.env', '.env.local',
]);

if (OUT === ROOT || OUT.startsWith(ROOT + sep)) {
  console.error(`Refusing to stage inside the app itself (${OUT}).`);
  process.exit(1);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

let copied = 0;
cpSync(ROOT, OUT, {
  recursive: true,
  filter(src) {
    const rel = relative(ROOT, src).split(sep).join('/');
    if (!rel) return true;
    if (EXCLUDE.has(rel) || rel.endsWith('.log')) return false;
    if (!existsSync(src)) return false;
    copied++;
    return true;
  },
});

// demo switch — must be evaluated before anything imports server/db.js
writeFileSync(join(OUT, 'api', '_demo-env.js'), `// Pitch-demo deployment: turn demo mode on before the app (and db.js) load.
// Imported first by api/index.js; ESM evaluates imports in order.
process.env.OCEANMIND_DEMO = '1';
delete process.env.DATABASE_URL; // the demo always runs on a seeded in-memory SQLite DB
delete process.env.OCEANMIND_TEST_AI;
`);

writeFileSync(join(OUT, 'api', 'index.js'), `// Vercel serverless entry for the PITCH DEMO deployment (generated by
// scripts/stage-demo-deploy.mjs). Same as the production entry, except that
// _demo-env.js switches demo mode on first.
import './_demo-env.js';
import { createApp } from '../server/app.js';

const app = createApp();

export default function handler(req, res) {
  return app(req, res);
}
`);

// same vercel.json as production (the build command builds the client)
const vercel = JSON.parse(readFileSync(join(ROOT, 'vercel.json'), 'utf8'));
writeFileSync(join(OUT, 'vercel.json'), `${JSON.stringify(vercel, null, 2)}\n`);

// Node: node:sqlite needs >= 22.13 (works on Vercel's 22.x and 24.x runtimes)
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
pkg.engines = { ...(pkg.engines ?? {}), node: '>=22.13' };
writeFileSync(join(OUT, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);

console.log(`Staged the pitch-demo deployment (${copied} entries) in:\n  ${OUT}\n`);
console.log('Next steps (not run by this script):');
console.log('  cd "<that folder>"');
console.log('  vercel link          # create/pick a NEW project, e.g. oceanmind-demo — never the production one');
console.log('  vercel deploy --prod # optional env: OCEANMIND_DEMO_SPEED (default 1), COOKIE_SECRET');
